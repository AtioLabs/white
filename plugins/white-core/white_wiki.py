"""Render the world model as readable wiki pages (the Town lesson).

Pages are regenerated from world.db, so the database stays the source of truth. The founder
reads them, and corrects anything by telling White, which updates the database.
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

from white_world import World  # type: ignore  # same package dir is on sys.path (see __init__)

HEADER = "<!-- Generated by White from world.db. Edit by telling White; manual edits are overwritten. -->\n"


def _confirmed(row: dict) -> str:
    return " ✓" if row.get("confirmed") else ""


def render(world: World, out_dir: Path, today: date | None = None) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    snap = world.snapshot(today)
    written: list[Path] = []

    def write(name: str, body: str) -> None:
        p = out_dir / name
        p.write_text(HEADER + body.rstrip() + "\n", encoding="utf-8")
        written.append(p)

    # Overview
    lines = ["# Now", ""]
    rw = snap["runway"]
    lines.append(f"**Runway:** {rw['months']} months as of {rw['as_of']} ({rw['source']})" if rw
                 else "**Runway:** unknown. Ask the founder.")
    lines += ["", f"**Overdue commitments:** {len(snap['overdue_commitments'])}",
              f"**Stalled pipeline items:** {len(snap['stalled_pipeline'])}",
              f"**Unhandled signals:** {len(snap['unhandled_signals'])}", "", "## Pipeline", ""]
    for r in snap["pipeline_counts"]:
        lines.append(f"- {r['kind']} / {r['stage']}: {r['n']}")
    write("now.md", "\n".join(lines))

    # People
    lines = ["# People", ""]
    for r in world._rows("SELECT p.*, o.name AS org FROM people p LEFT JOIN orgs o ON o.id=p.org_id ORDER BY p.name"):
        bits = [b for b in (r.get("role"), r.get("org")) if b]
        lines.append(f"## {r['name']}{_confirmed(r)}")
        if bits:
            lines.append(", ".join(bits))
        for label, key in (("Relationship", "relationship"), ("Warm path", "warm_path"),
                           ("Last contact", "last_contact"), ("Notes", "notes")):
            if r.get(key):
                lines.append(f"- {label}: {r[key]}")
        lines += [f"- Source: {r['source']}", ""]
    write("people.md", "\n".join(lines))

    # Pipeline
    lines = ["# Pipeline", ""]
    for r in world.pipeline():
        due = f" (due {r['next_due']})" if r.get("next_due") else ""
        who = " · ".join(b for b in (r.get("org"), r.get("person")) if b)
        lines.append(f"- **[{r['kind']}] {r['title']}**: {r['stage']}{(' · ' + who) if who else ''}")
        if r.get("next_step"):
            lines.append(f"  - Next: {r['next_step']}{due}")
        if r.get("signal"):
            lines.append(f"  - Signal: {r['signal']}")
        lines.append(f"  - Source: {r['source']}")
    write("pipeline.md", "\n".join(lines))

    # Commitments
    lines = ["# Commitments", "", "## Overdue", ""]
    lines += [f"- {c['owner']} → {c['to_whom'] or '?'}: {c['what']} (due {c['due']})"
              for c in snap["overdue_commitments"]] or ["- none"]
    lines += ["", "## Open", ""]
    lines += [f"- {c['owner']} → {c['to_whom'] or '?'}: {c['what']}" + (f" (due {c['due']})" if c['due'] else "")
              for c in snap["open_commitments"]] or ["- none"]
    write("commitments.md", "\n".join(lines))

    # Lessons
    lines = ["# Lessons (with evidence)", ""]
    for r in world._rows("SELECT * FROM lessons ORDER BY created DESC"):
        ev = ", ".join(json.loads(r["evidence"]))
        lines.append(f"- {r['lesson']}" + (f" [{r['topic']}]" if r.get("topic") else "") + f"\n  - Evidence: {ev}")
    write("lessons.md", "\n".join(lines))

    return written
